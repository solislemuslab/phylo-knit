// Main function for generating the D3 graph
function createD3Graph(updateLeafBox, dotString) {
    // clear the current list of nodes
    nodeVal = [];

    if(typeof(updateLeafBox) == "undefined")
        updateLeafBox = true;

    removeGraph();

    document.getElementById("loader").style.visibility = "hidden";
    selectbutton.disabled = true;
    refresher.style.visibility = "visible";
    refresher.disabled = false;

    selectbutton.disabled = true;
    console.log(dotString);
    console.log(d3.dot_from_string)
    
    var graph;
    
    // we don't need to do stupid file reading anymore!
    try {
        graph = d3.dot_from_string(dotString);

        console.log("graph prints");
        console.log(graph);
        GRAPH = graph;

        for (var i = 0; i < graph.links.length; i++) {
            if (typeof targetCounts.get(graph.links[i].target) === "undefined") {
                temp = [graph.links[i].source];
                targetCounts.set(graph.links[i].target, temp);
            } else if (targetCounts
                        .get(graph.links[i].target)
                        .includes(graph.links[i].source)
            ) {
                continue;
            } else {
                targetCounts
                    .get(graph.links[i].target)
                    .push(graph.links[i].source);
            }
        }
        console.log(targetCounts);

        console.log("GRAPH HERE")
        console.log(graph)

        // figure out which node is the root node, if we don't already know
        for(var i = 0; i < graph.nodes.length; i++) {
            if(targetCounts.get(graph.nodes[i].id) == undefined) {
                ROOT_NAME = graph.nodes[i].id;
                break;
            }
        }

        // fix the root node in place
        for(var i = 0; i < graph.nodes.length; i++) {
            if(graph.nodes[i].id == ROOT_NAME) {
                graph.nodes[i].fx = 0;
                graph.nodes[i].fy = 0;
                break;
            }
        }

        // Get source and target updates
        var targetVals = ""
        var sourceVals = ""
        
        for(var i = 0 ; i < graph.links.length; i++){
            sourceVals = sourceVals + " " + graph.links[i].source
            targetVals = targetVals + " " + graph.links[i].target
        }

        // add all of the links (paths) to the svg and set their attributes
        var path = svg
            // set up the svg organization
            .append("svg:g")
            .attr("class", "links")
            .selectAll("path")
            .data(graph.links)
            .enter()
            // add the arrow head
            .append("svg:path")
            .attr("marker-end", "url(#end)")
            .attr("fill", "none")
            .style("stroke", "black")
            .style("stroke-width", STROKE_WIDTH)
        nodeNum = graph.nodes.length;

        // add all of the nodes to the svg and set their attributes
        var node = svg
            .append("g")
            .attr("class", "nodes")
            .selectAll("circle")
            .data(graph.nodes)
            .enter()
            .append("g");

        node.append("circle")
            .attr("r", function (d) {
                console.log(d);
                var valueOfNode = d.id.toString();
                if (!isInternalNode(valueOfNode)) {
                    nodeVal.push(valueOfNode);
                    console.log("LEAF");
                    return LEAF_RADIUS;
                }
                if(isRootNode(valueOfNode))
                    return LEAF_RADIUS
                else
                    return INTERNAL_NODE_RADIUS;
            })
            .attr("d.x", width/2)
            .attr("d.y", height/2)
            .attr("node_name", function(d) { return d.id.toString(); })
            .style("fill", function (d) {
                var valueOfNode = d.id.toString();

                return isHybridNode(valueOfNode)
                    ? HYBRID_COLOR
                    : isRootNode(valueOfNode)
                    ? ROOT_COLOR
                    : isInternalNode(valueOfNode)
                    ? INTERNAL_COLOR
                    : isNamedInternalNode(valueOfNode)
                    ? INTERNAL_NAMED_COLOR
                    : LEAF_COLOR;
                
            })
            .style("stroke", "black")
            .style("stroke-width", STROKE_WIDTH)
            .call(d3.drag()
                .on("start", dragstarted)
                .on("drag", dragged)
                .on("end", dragended)
            )
            .on("click", clicked);
        node.append("text")
            .attr("x", 12)
            .attr("dy", "0.3em")
            .attr("dx", "-0.1em")
            .style("font-size", FONT_SIZE)
            .style("font-family", FONT_FAMILY)
            .style("text-anchor", "middle")
            .text(function (d) {
                var valueOfNode = d.id.toString();
                if(isInternalNode(valueOfNode)) {
                    return "";
                } else if(isHybridNode(valueOfNode)) {
                    if(INTERNAL_NODE_RADIUS < 15)
                        return "";
                    return "#" + d.id.substr(4, d.id.length-4);
                } else if(isNamedInternalNode(valueOfNode)) {
                    if(INTERNAL_NODE_RADIUS < 15)
                        return "";
                    if(DISPLAY_NAMED_INTERNAL_NODE_NAMED)
                        return d.id.substr(8, d.id.length-8);
                    else
                        return "";
                }
                return d.id;
            });

        simulation.nodes(graph.nodes).on("tick", ticked);
        console.log("link check")
        console.log(graph.links)

        if(AUTO_UPDATE_SETTINGS) {
            if(graph.nodes.length <= 20) {
                $('#node-radius-slider')[0].value = 115;
                updateLeafRadius();
                $('#font-size-slider')[0].value = 91;
                updateFontSize();
                $('#link-distance-slider')[0].value = 350;
                updateLinkDistance();
                $('#link-strength-slider')[0].value = 530;
                updateLinkStrength();
            } else if(graph.nodes.length <= 40) {
                $('#node-radius-slider')[0].value = 115;
                updateLeafRadius();
                $('#font-size-slider')[0].value = 90;
                updateFontSize();
                $('#link-distance-slider')[0].value = 250;
                updateLinkDistance();
                $('#link-strength-slider')[0].value = 530;
                updateLinkStrength();
            } else {
                $('#node-radius-slider')[0].value = 115;
                updateLeafRadius();
                $('#font-size-slider')[0].value = 90;
                updateFontSize();
                $('#link-distance-slider')[0].value = 250;
                updateLinkDistance();
                $('#link-strength-slider')[0].value = 530;
                updateLinkStrength();
            }
        }

        // These functions set of the physics between nodes
        simulation.force('link', d3.forceLink(graph.links).distance(LINK_DISTANCE).id(n => n.id).strength(LINK_STRENGTH))     // edges
        simulation.force('charge', d3.forceManyBody().strength(MANY_BODY_STRENGTH));                     // node repulsion/attraction
        // simulation.force('center', d3.forceCenter(width / 2, height / 2).strength(0));                  // network centering
        simulation.force('collision', d3.forceCollide().radius(COLLISION_RADIUS));                        // stop collisions

        if(FORCEX_STRENGTH != 0)
            simulation.force('forceX', d3.forceX(FORCEX_X).strength(FORCEX_STRENGTH));
        if(FORCEY_STRENGTH != 0)
            simulation.force('forceY', d3.forceY(FORCEY_Y).strength(FORCEY_STRENGTH));

        // stops the upper left hand corner bug (though the result still isn't amazing)
        // it seems that running `simulation.alphaDecay(0.001).alpha(1).restart()` multiple times after initialization leads to good results
        // check out: https://github.com/d3/d3/issues/1519 perhaps
        simulation.alphaDecay(0.001).alpha(1).restart();
        svg.call(zoom.transform, d3.zoomIdentity.translate(width/2, height/2).scale(0.15));

        // set up the Displayed Leaves list
        if(updateLeafBox) {
            console.log("\t\t\tCREATING BOXES")
            console.log("\t\t\tCREATING BOXES")
            console.log("\t\t\tCREATING BOXES")
            console.log("\t\t\tCREATING BOXES")
            console.log(updateLeafBox);
            createboxes();
        }

        // raise the legend above everything else
        legendContainer.raise();

        function ticked() {
            path.attr("d", function (d) {
                return (
                    "M" +
                    d.source.x +
                    "," +
                    d.source.y +
                    "L" +
                    d.target.x +
                    "," +
                    d.target.y
                );
            });
            node.attr("transform", function (d) {
                return "translate(" + d.x + "," + d.y + ")";
            });
        }
    } catch(exceptionVar) {
        alert("An error was encountered with your input. See the console for more details.");
        console.log(exceptionVar);
        return;
    }
}

